                b = max(cands, key=lambda x: len(bn[x]))
                ok = bool(set(pl) & set(brands[b]))
                rows.append([prod, b, 'Auto' if ok else 'Review', 'name match' if ok else 'name match, but IQVIA line differs from the sales lines', round(tot), ', '.join(pl), ', '.join(brands[b])])
                continue
