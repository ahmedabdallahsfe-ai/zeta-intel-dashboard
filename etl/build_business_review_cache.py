    agg = collections.defaultdict(Z)
    months = None
    for cname, cl in d['clusters'].items():
        months = cl.get('months') or months
        for cu in cl['customers']:
            a = agg['ALL']; seg = cu.get('bridgeSegment'); a['n'][seg] += 1; a['v'][seg] += cu.get('value') or 0
