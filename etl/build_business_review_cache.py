def build_execution():
    r, _ = load_b64('records.data.js')
    d, _ = load_b64('dashboard.data.js')
    dims = d['dimensions']
    F = {n: i for i, n in enumerate(r['fields'])}
    periods = dims['periods']; teams = dims['teams']; classes = dims['classes']
    resigned_idx = dims['statuses'].index('Resigned') if 'Resigned' in dims['statuses'] else -1
    team_line = {}
    for t in teams:
        ln = KEY2LINE.get(K(t))
        if ln:
            team_line[teams.index(t)] = ln
    is_a = [str(c).upper().startswith('A') for c in classes]
    Z = lambda: {'cov': 0, 'rf': 0, 'n': 0, 'vis': 0, 'tgt': 0, 'aRf': 0, 'aN': 0, 'act': set(), 'res': set(), 'below': 0, 'over': 0}
    g = collections.defaultdict(Z)
    fi = F
    for row in r['rows']:
        ln = team_line.get(row[fi['teamIdx']])
        if not ln:
            continue
        key = (ln, row[fi['periodIdx']])
        s = g[key]
        if row[fi['isActive']]:
            s['act'].add(row[fi['employeeIdx']])
            if row[fi['isExempt']]:
                continue
            pr = row[fi['proratedFrequency']] if row[fi['proratedFrequency']] is not None else -1
            vis = row[fi['visits']] or 0
            tgt = pr if pr >= 0 else (row[fi['frequency']] or 0)
            rf = (1 if vis >= pr else 0) if pr >= 0 else row[fi['rightFreq']]
            s['cov'] += row[fi['coveredDoctor']]; s['rf'] += rf; s['n'] += 1
            s['vis'] += vis; s['tgt'] += tgt
            if rf == 0:
                s['below'] += 1
            elif vis > tgt:
                s['over'] += 1
            ci = row[fi['classIdx']]
            if ci is not None and 0 <= ci < len(is_a) and is_a[ci]:
                s['aRf'] += rf; s['aN'] += 1
        elif row[fi['statusIdx']] == resigned_idx:
            s['res'].add(row[fi['employeeIdx']])
    del r
    res_ids = collections.defaultdict(set)
    for (ln, pi), s in g.items():
        res_ids[ln] |= s['res']
    out = {'periods': periods, 'lines': {}, 'resIds': res_ids}
    for ln in ALL_LINES:
        series = []
        for pi, p in enumerate(periods):
            s = g.get((ln, pi))
            if not s or not s['n']:
                series.append(None); continue
            series.append({'cov': s['cov'], 'rf': s['rf'], 'n': s['n'], 'vis': s['vis'], 'tgt': s['tgt'],
                           'aRf': s['aRf'], 'aN': s['aN'], 'hc': len(s['act']), 'res': len(s['res']),
                           'below': s['below'], 'over': s['over']})
        out['lines'][ln] = series
    # validation hook vs the Coverage page's own August team figures
    tc = {K(t['team']): t for t in d['teamComparison']}
    worst = 0
    for ln in ALL_LINES:
        s = out['lines'][ln][-1]
        t = tc.get(K(TEAM_OF.get(ln, ln)))
        if s and t:
            worst = max(worst, abs(s['cov'] / s['n'] - t['coveragePct']))
    # Right Frequency follows js/analytics.js (visits >= prorated target when a
    # prorated target exists), i.e. what the live Coverage page shows; the ETL's
    # precomputed teamComparison can differ by <1 pt on prorated rows, so only
    # Coverage is checked strictly here.
    log(f'execution: {len(periods)} periods; max |coverage diff| vs Coverage page {periods[-1]} team figures = {worst:.4f}')
    if worst > 0.001:
        log('  *** WARNING: coverage differs from the Coverage page -- check the rule mirror')
    return out


