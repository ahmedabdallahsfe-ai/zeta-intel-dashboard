def roll(lines, sales, exe, mgr):
    months = sales['months']
    tot = collections.defaultdict(lambda: [0.0] * len(months))
    for ln in lines:
        if len(lines) > 1 and ln in NOT_IN_BU_TOTAL:
            continue
        s = sales['lines'][ln]
        for k in ('mA', 'mO', 'mS', 'mW', 'mVol', 'mPrice', 'mOther'):
            for i, v in enumerate(s[k]):
                tot[k][i] += v
    periods = exe['periods']
    ex = []
    for pi in range(len(periods)):
        acc = collections.Counter()
        for ln in lines:
            s = exe['lines'][ln][pi]
            if s:
                acc.update({k: v for k, v in s.items()})
        ex.append(dict(acc) if acc.get('n') else None)
    cm = []
    for i in range(len(mgr['coachMonths'])):
        acc = collections.Counter()
        for ln in lines:
            x = mgr['lines'][ln]['coach'][i]
            if x:
                acc.update(x)
        cm.append(dict(acc) if acc.get('days') else None)
    fm = []
    for i in range(len(mgr['fieldMonths'])):
        tw = 0; n = 0; low = 0
        for ln in lines:
            x = mgr['lines'][ln]['field'][i]
            if x:
                tw += x['avg'] * x['n']; n += x['n']; low += x['low']
        fm.append({'avg': tw / n, 'low': low, 'n': n} if n else None)
    res = set()
    for ln in lines:
        res |= exe['resIds'].get(ln, set())
    return {'sales': {k: [round(v) for v in tot[k]] for k in ('mA', 'mO', 'mS', 'mW', 'mVol', 'mPrice', 'mOther')}, 'exec': ex, 'coach': cm, 'field': fm, 'resignedYtd': len(res)}


