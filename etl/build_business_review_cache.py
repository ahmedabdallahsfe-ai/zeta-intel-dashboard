MON = ['', 'Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec']


def pct(x, d=0):
    return 'n/a' if x is None else f'{100*x:.{d}f}%'


def pts(x, d=1):
    return 'n/a' if x is None else f'{100*x:+.{d}f} pts'


def comments(name, kind, E, sales_months, exe_periods, coach_months, field_months, iq, brands_iq, brands_sales, lines):
    """Returns {headline, strengths[], concerns[], market[], questions[]}. Every
    item is {text, tag:'FACT', conf, impact}: Ahmed 2026-09-26 "don't make any
    hypothesis" -- only statements read or computed directly from the data.
    impact = EGP at stake where one can be computed (used to rank, biggest first)."""
    S = E['sales']; mA, mO, mS = S['mA'], S['mO'], S['mS']
    ytdA, ytdO, ytdS = sum(mA), sum(mO), sum(mS)
    ach = 100 * ytdA / ytdO if ytdO else None
    lastAch = 100 * mA[-1] / mO[-1] if mO[-1] else None
    h1A, h1O = sum(mA[:6]), sum(mO[:6])
    recA, recO = sum(mA[6:]), sum(mO[6:])
    h1Ach = 100 * h1A / h1O if h1O else None
    recAch = 100 * recA / recO if recO else None
    months_below = sum(1 for a, o in zip(mA, mO) if o and a / o < 0.9)
    ex = [x for x in E['exec'] if x]
    exL = E['exec'][-1]
    cov = exL['cov'] / exL['n'] if exL else None
    rf = exL['rf'] / exL['n'] if exL else None
    ytdCov = sum(x['cov'] for x in ex) / sum(x['n'] for x in ex) if ex else None
    ytdRf = sum(x['rf'] for x in ex) / sum(x['n'] for x in ex) if ex else None
    firstCov = ex[0]['cov'] / ex[0]['n'] if ex else None
    firstRf = ex[0]['rf'] / ex[0]['n'] if ex else None
    aRf = exL['aRf'] / exL['aN'] if exL and exL.get('aN') else None
    visit = exL['vis'] / exL['tgt'] if exL and exL['tgt'] else None
    cl = next((x for x in reversed(E['coach']) if x), None)
    cpd = cl['vis'] / cl['days'] if cl else None
    coached = cl['coached'] / cl['team'] if cl and cl['team'] else None
    fl = E['field'][-1]
    supply = (ytdO - ytdS) / ytdO if ytdO and ytdS and ytdO > ytdS else 0
    cpd_t = TH['cpdChcSales'] if lines == ['CHC_SALES'] else TH['cpd']
    hc = exL['hc'] if exL else None
    res_ytd = E.get('resignedYtd', 0)

    st, co, mk, qs = [], [], [], []
    F = lambda t, imp=None: {'text': t, 'tag': 'FACT', 'conf': 90, 'impact': round(abs(imp)) if imp is not None else None}

    # ---- sales
    if ach is not None:
        line = f'YTD sales {ytdA/1e6:.1f}M vs Official target {ytdO/1e6:.1f}M = {ach:.0f}% ({"above" if ach >= 100 else "below"} target by {abs(ytdA-ytdO)/1e6:.1f}M).'
        ytd_item = F(line, ytdA - ytdO)
        (st if ach >= 100 else co).append(ytd_item)
    if h1Ach is not None and recAch is not None:
        if recAch - h1Ach >= 10:
            st.append(F(f'Momentum improving: Jul–Aug achievement {recAch:.0f}% vs Jan–Jun {h1Ach:.0f}%.', recA - recO))
        elif h1Ach - recAch >= 10:
            co.append(F(f'Momentum slowing: Jul–Aug achievement {recAch:.0f}% vs Jan–Jun {h1Ach:.0f}%.', recA - recO))
    if months_below >= 5:
        co.append(F(f'Below 90% of target in {months_below} of {len(mA)} months.'))
        qs.append('What was the target built on (run-rate, market growth, launch curve), and is it still realistic for Sep–Dec?')
    if supply > 0.03:
        co.append(F(f'Stock shortage explains {pct(supply)} of YTD target (Shortage target {ytdS/1e6:.1f}M vs Official {ytdO/1e6:.1f}M).', ytdO - ytdS))
        qs.append('Which SKUs are still short, what is the confirmed recovery date, and how are priority customers being protected?')
    # ---- brand concentration and weak brands (sales cache)
    bs = []
    for ln in lines:
        if len(lines) > 1 and ln in NOT_IN_BU_TOTAL:
            continue
        bs += brands_sales.get(ln, [])
    tA = sum(b['ytdA'] for b in bs)
    if bs and tA > 0:
        top = max(bs, key=lambda b: b['ytdA'])
        sh = top['ytdA'] / tA
        if sh >= 0.5 and len(bs) > 1:
            co.append(F(f'Concentration risk: {top["brand"]} is {pct(sh)} of YTD sales.'))
            qs.append(f'What is the plan if {top["brand"]} slows down, and which brand is ready to take a bigger share?')
        weak = [b for b in bs if b['ytdO'] > 0.05 * sum(x['ytdO'] for x in bs) and b['ytdA'] / b['ytdO'] < 0.8]
        weak.sort(key=lambda b: b['ytdA'] - b['ytdO'])
        if weak:
            co.append(F('Brands below 80% YTD (≥5% of target): ' + ', '.join(f'{b["brand"]} {100*b["ytdA"]/b["ytdO"]:.0f}% ({(b["ytdA"]-b["ytdO"])/1e6:+.1f}M)' for b in weak[:4]) + '.', sum(b['ytdA'] - b['ytdO'] for b in weak[:4])))
            qs.append(f'What is the recovery plan for {weak[0]["brand"]} ({(weak[0]["ytdA"]-weak[0]["ytdO"])/1e6:+.1f}M YTD gap), with monthly milestones?')
        strong = [b for b in bs if b['ytdO'] > 0.05 * sum(x['ytdO'] for x in bs) and b['ytdA'] / b['ytdO'] >= 1.1]
        strong.sort(key=lambda b: -(b['ytdA'] - b['ytdO']))
        if strong:
            st.append(F('Brands above 110% YTD: ' + ', '.join(f'{b["brand"]} {100*b["ytdA"]/b["ytdO"]:.0f}% ({(b["ytdA"]-b["ytdO"])/1e6:+.1f}M)' for b in strong[:4]) + '.', sum(b['ytdA'] - b['ytdO'] for b in strong[:4])))

    # ---- execution
    if cov is not None:
        good = cov >= TH['cov'] and rf > TH['rf']
        msg = f'{exe_periods[-1]} execution: Coverage {pct(cov,1)}, Right Frequency {pct(rf,1)} (bar ≥90% / >80%); YTD {pct(ytdCov,1)} / {pct(ytdRf,1)}.'
        (st if good else co).append(F(msg))
        if firstCov is not None and cov - firstCov >= 0.05:
            st.append(F(f'Coverage up {100*(cov-firstCov):.0f} pts since {exe_periods[0]} ({pct(firstCov)} → {pct(cov)}).'))
        if firstRf is not None and rf - firstRf >= 0.05:
            st.append(F(f'Right Frequency up {100*(rf-firstRf):.0f} pts since {exe_periods[0]} ({pct(firstRf)} → {pct(rf)}).'))
        if aRf is not None and aRf < rf - 0.03:
            co.append(F(f'A-class customers get less frequency than average: A-class RF {pct(aRf)} vs {pct(rf)} overall.'))
            qs.append('Why do A-class customers get lower frequency than B/C, and when will the call plans be re-balanced?')
        if not good:
            qs.append('Which territories drive the gap to Coverage 90% / Right Frequency 80%, and what is the weekly recovery plan?')
    if visit is not None and visit < TH['visit']:
        co.append(F(f'Visit achievement {pct(visit,1)} of planned visits in {exe_periods[-1]}.'))
    # ---- managers
    if cpd is not None:
        if cpd < cpd_t - 0.5:
            co.append(F(f'Coaching intensity {cpd:.1f} calls per coaching day vs target {cpd_t:.0f}; {pct(coached)} of reps coached.'))
            qs.append('How will DMs raise double-visit intensity to target, and who is not coaching every rep monthly?')
        elif coached is not None and coached >= 0.95:
            st.append(F(f'Coaching: {pct(coached)} of reps coached at {cpd:.1f} calls per coaching day.'))
    if fl and fl['avg'] < TH['field']:
        co.append(F(f'DM field days {pct(fl["avg"])} of target in {field_months[-1]} ({fl["low"]} of {fl["n"]} DMs below 70%).'))
        qs.append('Which DMs are below 70% field days, and what is taking them out of the field?')
    if hc and res_ytd:
        rate = res_ytd / (hc + res_ytd)
        if rate > 0.08:
            co.append(F(f'People: {res_ytd} resignations YTD ({exe_periods[0]}–{exe_periods[-1]}) on {hc} active reps now.'))
            qs.append('What are the top exit reasons, and which vacant territories hold A-class customers?')

    # ---- IQVIA market
    if iq:
        mk.append(F(f'IQVIA YTD: Zeta share {pct(iq["shareSU"],2)} units / {pct(iq["shareV"],2)} value, vs {pct(iq["shareSUp"],2)} / {pct(iq["shareVp"],2)} last year. Value growth: market {pct(iq["mktG"],1) if iq["mktG"] is not None else "n/a"}, Zeta {pct(iq["zG"],1) if iq["zG"] is not None else "n/a"}. EVI {iq["evi"]} (units).'))
        if iq['evi'] is not None:
            dV = (iq['shareV'] or 0) - (iq['shareVp'] or 0)
            if iq['evi'] >= 105:
                st.append(F(f'Zeta grew faster than its market in IQVIA (EVI {iq["evi"]}, units share {pts((iq["shareSU"] or 0)-(iq["shareSUp"] or 0),2)} vs last year).', iq['mktV'] * dV))
            elif iq['evi'] <= 95:
                co.append(F(f'Zeta grew slower than its market in IQVIA (EVI {iq["evi"]}, units share {pts((iq["shareSU"] or 0)-(iq["shareSUp"] or 0),2)} vs last year).', iq['mktV'] * dV))
                qs.append('Which competitor is taking the share, in which market, and what is the counter-plan?')
        if iq['shareVm'] is not None and iq['shareVpm'] is not None and abs(iq['shareVm'] - iq['shareVpm']) >= 0.005:
            mk.append(F(f'Latest month: value share {pct(iq["shareVm"],2)} vs {pct(iq["shareVpm"],2)} the month before ({pts(iq["shareVm"]-iq["shareVpm"],2)}).'))
        if iq['rank'] and iq['rankP'] and iq['rank'] != iq['rankP']:
            mk.append(F(f'Zeta rank in this market: #{iq["rank"]} (last year #{iq["rankP"]}) of {iq["nCorps"]} companies.'))
        elif iq['rank']:
            mk.append(F(f'Zeta rank in this market: #{iq["rank"]} of {iq["nCorps"]} companies (unchanged).'))
        g = [x for x in iq['gainers'] if not x['zeta'] and x['dShare'] > 0.002]
        l = [x for x in iq['losers'] if not x['zeta'] and x['dShare'] < -0.002]
        if g:
            mk.append(F('Competitors gaining share: ' + ', '.join(f'{x["corp"]} {pts(x["dShare"],2)} (growth {pct(x["growth"])})' for x in g[:3]) + '.'))
        if l:
            mk.append(F('Competitors losing share: ' + ', '.join(f'{x["corp"]} {pts(x["dShare"],2)}' for x in l[:3]) + '.'))
        # sell-in vs in-market
        if ach is not None and iq['evi'] is not None and ach >= 100 and iq['evi'] < 100:
            co.append(F(f'Sell-in is {ach:.0f}% of target while IQVIA in-market sales grew slower than the market (EVI {iq["evi"]}).', ytdA - ytdO))
            qs.append('How many weeks of stock do distributors hold, and does sell-out support the sell-in trend?')
    # brand-level market comments
    bl = [b for b in brands_iq if b.get('shareP') is not None]
    for b in sorted(bl, key=lambda b: -(b['share'] - b['shareP']))[:2]:
        if b['share'] - b['shareP'] > 0.005:
            gtxt = f'growth {pct(b["growth"])}' if b['growth'] is not None else 'new in this market'
            st.append(F(f'{b["name"]} gained {pts(b["share"]-b["shareP"])} value share in {b["dm1"]} ({pct(b["shareP"],1)} → {pct(b["share"],1)}), {gtxt} vs market {pct(b["mktG"])}.', b['mktV'] * (b['share'] - b['shareP'])))
    for b in sorted(bl, key=lambda b: (b['share'] - b['shareP']))[:3]:
        if b['share'] - b['shareP'] < -0.005:
            who = b.get('topGainer')
            extra = f'; biggest gainer in that market: {who["prod"]} ({who["corp"]}) {pts(who["share"]-who["shareP"])}' if who else ''
            co.append(F(f'{b["name"]} lost {pts(b["shareP"]-b["share"])[1:]} value share in {b["dm1"]} ({pct(b["shareP"],1)} → {pct(b["share"],1)}){extra}.', b['mktV'] * (b['share'] - b['shareP'])))
            qs.append(f'What is the plan to win back share for {b["name"]} in {b["dm1"]}?')

    # new competitors in Zeta brands' markets
    seen_ne = set()
    for b in brands_iq:
        for ne in b.get('newEntrants') or []:
            k = (ne['prod'], b['dm1'])
            if k in seen_ne:
                continue
            seen_ne.add(k)
            mk.append(F(f'New competitor in {b["dm1"]} ({b["name"]}\'s market): {ne["prod"]} ({ne["corp"]}) reached {pct(ne["share"],1)} value share YTD with no sales in the same months last year.', b['mktV'] * ne['share']))
            qs.append(f'How is {b["name"]} responding to the launch of {ne["prod"]} ({ne["corp"]})?')
    # volume vs price/mix split of the YTD gap
    vol, prc, oth = sum(S['mVol']), sum(S['mPrice']), sum(S['mOther'])
    gap = ytdA - ytdO
    if ytdO and abs(gap) > 0.02 * ytdO and (vol or prc) and ach is not None:
        ytd_item['text'] += (f' Split: volume (units) {vol/1e6:+.1f}M, price/mix {prc/1e6:+.1f}M'
                             + (f', months without unit targets {oth/1e6:+.1f}M' if abs(oth) >= 0.05e6 else '') + '.')
    # sell-in vs IQVIA in-market by brand (company level, mapped brands only)
    for g in E.get('sellout') or []:
        # small bases give meaningless % (e.g. launches): need >= 0.25M/month in both sources
        if g['ytdSi'] < 1e6 or g['siChg'] is None or g['imChg'] is None or g['siBase'] < 250e3 or g['imBase'] < 250e3:
            continue
        diff = g['siChg'] - g['imChg']
        if abs(diff) >= 0.20:
            rb, re_ = g['baseMonths'], g['recentMonths']
            txt = (f'{g["name"]}: sell-in {MON[int(re_[0][5:])]}–{MON[int(re_[-1][5:])]} {g["siChg"]*100:+.0f}% vs the {MON[int(rb[0][5:])]}–{MON[int(rb[1][5:])]} monthly average; '
                   f'IQVIA in-market {g["imChg"]*100:+.0f}% over the same months (IQVIA: {", ".join(g["iqvia"])}).')
            imp = 2 * (g['siRecent'] - g['siBase'] * (1 + g['imChg']))
            mk.append(F(txt, imp))
            if diff > 0:
                qs.append(f'What is the distributor stock position for {g["name"]}, given sell-in grew faster than IQVIA in-market?')
    # customer base
    CU = E.get('customers')
    if CU and CU['total']:
        c, v = CU['counts'], CU['values']
        active = c['New'] + c['Retained'] + c['Reactivated']
        txt = (f'Customers (pharmacies) buying these products in {MON[int(sales_months[-1][5:])]}: {active:,} '
               f'({c["Retained"]:,} retained, {c["Reactivated"]:,} reactivated, {c["New"]:,} new); '
               f'{c["Lost"]:,} bought in {MON[int(sales_months[-2][5:])]} but not in {MON[int(sales_months[-1][5:])]} (their YTD value {v["Lost"]/1e6:.1f}M).')
        (co if c['Lost'] > c['New'] + c['Reactivated'] else st).append(F(txt, v['Lost']))
        if c['Lost'] > c['New'] + c['Reactivated']:
            qs.append(f'What is the plan to win back the {c["Lost"]:,} pharmacies that bought in {MON[int(sales_months[-2][5:])]} but not in {MON[int(sales_months[-1][5:])]}?')

    # full-year landing
    LD = E.get('landing')
    if LD and LD['fy']:
        need = LD['required']; gapfy = LD['landing'] - LD['fy']
        pm = LD['paceMonths']; nxt = int(sales_months[-1][5:]) + 1
        pace_lbl = f'{MON[int(pm[0][5:])]}–{MON[int(pm[-1][5:])]}'; rem_lbl = f'{MON[nxt]}–Dec' if nxt < 12 else 'Dec'
        txt = (f'Full year: at the {pace_lbl} pace ({LD["pace"]/1e6:.1f}M a month) the year closes at {LD["landing"]/1e6:.1f}M vs the {LD["fy"]/1e6:.1f}M target ({100*LD["landing"]/LD["fy"]:.0f}%). '
               f'Reaching the target needs {need/1e6:.1f}M a month for {rem_lbl} ({(need/LD["pace"]-1)*100:+.0f}% vs the current pace).')
        (st if gapfy >= 0 else co).append(F(txt, gapfy))
        if gapfy < 0:
            qs.append(f'What is the month-by-month plan to deliver {need/1e6:.1f}M a month from {MON[nxt]}?')

    # rank by EGP at stake (largest first); items without an EGP value keep their order after them
    def rank(items):
        with_imp = sorted([x for x in items if x.get('impact')], key=lambda x: -x['impact'])
        return with_imp + [x for x in items if not x.get('impact')]
    st, co = rank(st), rank(co)
    mk = mk[:1] + rank(mk[1:])

    # headline
    parts = []
    if ach is not None:
        parts.append(f'{name} closed Jan–{MON[int(sales_months[-1][5:])]} YTD at {ach:.0f}% of Official target ({ytdA/1e6:.1f}M)')
    if iq and iq['evi'] is not None:
        parts.append(f'{"gaining" if iq["evi"] >= 100 else "losing"} ground in IQVIA (EVI {iq["evi"]}, share {pts((iq["shareSU"] or 0)-(iq["shareSUp"] or 0),2)})')
    if cov is not None:
        parts.append(f'execution at {pct(cov)} coverage / {pct(rf)} Right Frequency vs the 90/80 bar')
    headline = ', '.join(parts) + '.'
    # dedupe questions, keep order
    seen = set(); qd = []
    for q in qs:
        if q not in seen:
            seen.add(q); qd.append(q)
    return {'headline': headline, 'strengths': st, 'concerns': co, 'market': mk, 'questions': qd[:8]}


