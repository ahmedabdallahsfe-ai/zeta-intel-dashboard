def K(s):
    s = str(s or '').upper().replace('SALES', 'S').replace('NEUROSCIENCE', 'NEURO').replace('DIABETES', 'DIAB').replace('CNS', 'NEURO')
    return re.sub(r'[^A-Z]', '', s)
KEY2LINE = {K(l): l for l in ALL_LINES}


def load_b64(fname):
    raw = open(os.path.join(CACHE, fname), encoding='utf-8').read()
    m = re.search(r'b64Data"?\s*:\s*"([^"]+)"', raw)
    if not m:
        sys.exit(f'[business_review] ERROR: {fname} has no b64Data')
    return json.loads(gzip.decompress(base64.b64decode(m.group(1)))), raw


def log(msg):
    print(f'[business_review] {msg}', flush=True)


def div(a, b):
    return (a / b) if b else None


# ============================================================ 1. SALES
def build_sales():
    c, _ = load_b64('sales.data.js')
    L = c['lookups']['lines']; M = c['lookups']['months']; B = c['lookups']['brands']
    months = sorted(m for m in M if re.match(r'2026-\d\d$', m))
    last = months[-1]
    line_m = collections.defaultdict(lambda: collections.defaultdict(float))
    brand = collections.defaultdict(lambda: collections.defaultdict(float))
    for r in c['rows']:
        mask = r[17]
        if mask & 2:          # Tender excluded (Non-Tender convention)
            continue
        m = M[r[0]]
        if m not in months:
            continue
        ln = L[r[1]]
        if ln not in LINE_BU:
            continue
        if mask & 16:
            if mask & 64:
                key = 'S'
            elif mask & 32:
                key = 'O'
            else:
                key = 'W'
            line_m[ln][m + key] += r[21]
            line_m[ln][m + key + 'q'] += r[20]
            brand[(ln, B[r[2]])][m + key] += r[21]
        else:
            line_m[ln][m + 'A'] += r[19]
            line_m[ln][m + 'Aq'] += r[18]
            brand[(ln, B[r[2]])][m + 'A'] += r[19]
    del c
    out = {'months': months, 'last': last, 'lines': {}, 'brands': {}}
    for ln in ALL_LINES:
        x = line_m.get(ln, {})
        out['lines'][ln] = {
            'mA': [round(x.get(m + 'A', 0)) for m in months],
            'mO': [round(x.get(m + 'O', 0)) for m in months],
            'mS': [round(x.get(m + 'S', 0)) for m in months],
            'mW': [round(x.get(m + 'W', 0)) for m in months],
        }
        # Volume / price-mix split of the gap vs Official target, per month:
        # target price p = O / Oq; volume = (Aq - Oq) * p; price/mix = A - Aq * p
        # (volume + price/mix = A - O exactly). Months with a target value but
        # no target units go to 'other'.
        vol, prc, oth = [], [], []
        for m in months:
            A, O, Aq, Oq = x.get(m + 'A', 0), x.get(m + 'O', 0), x.get(m + 'Aq', 0), x.get(m + 'Oq', 0)
            if O and Oq:
                p = O / Oq
                vol.append(round((Aq - Oq) * p)); prc.append(round(A - Aq * p)); oth.append(0)
            else:
                vol.append(0); prc.append(0); oth.append(round(A - O) if O else 0)
        out['lines'][ln].update({'mVol': vol, 'mPrice': prc, 'mOther': oth})
    for (ln, b), x in brand.items():
        a = sum(x.get(m + 'A', 0) for m in months)
        o = sum(x.get(m + 'O', 0) for m in months)
        if a <= 0 and o <= 0:
            continue
        out['brands'].setdefault(ln, []).append({
            'brand': b, 'ytdA': round(a), 'ytdO': round(o),
            'lastA': round(x.get(last + 'A', 0)), 'lastO': round(x.get(last + 'O', 0)),
            'prevA': round(x.get(months[-2] + 'A', 0)) if len(months) > 1 else 0,
        })
    for ln in out['brands']:
        out['brands'][ln].sort(key=lambda r: -r['ytdA'])
    bm = collections.defaultdict(lambda: [0.0] * len(months)); blines = collections.defaultdict(set)
    for (ln, b), x in brand.items():
        blines[b].add(ln)
        if ln in NOT_IN_BU_TOTAL:
            continue
        for i, m in enumerate(months):
            bm[b][i] += x.get(m + 'A', 0)
    out['brandMonthly'] = {b: [round(v) for v in vals] for b, vals in bm.items()}
    out['brandLines'] = {b: sorted(v) for b, v in blines.items()}
    log(f'sales: {len(months)} months ({months[0]}..{last}), {sum(len(v) for v in out["brands"].values())} line-brands')
    return out


