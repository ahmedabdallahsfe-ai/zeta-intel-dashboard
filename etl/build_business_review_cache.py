def build_fy_targets():
    """Full-year Official targets that exist in the source files. Today only the
    CHC BU has one: CHC_BU_YTD_PERFROMANCE.xlsx sheet 'New CHC Target' (annual
    value + CHC_SALES % of CHC + monthly phasing). Other lines have no Sep-Dec
    target loaded anywhere, so they get none -- nothing is extrapolated."""
    out = {}
    path = os.path.join(ROOT, 'ZETA SALES_2026', 'CHC_BU_YTD_PERFROMANCE.xlsx')
    try:
        from python_calamine import CalamineWorkbook
        rows = CalamineWorkbook.from_path(path).get_sheet_by_name('New CHC Target').to_python()
    except Exception as e:
        log(f'FY targets: New CHC Target sheet not read ({e}) -- no full-year targets')
        return out
    annual = pct_sales = None; phasing = None
    for r in rows:
        lab = str(r[0]).strip() if r and r[0] is not None else ''
        vals = [v for v in r[1:] if isinstance(v, (int, float))]
        if lab.startswith('Annual Target Value') and vals:
            annual = float(vals[0])
        elif lab.startswith('CHC_SALES target as %') and vals:
            pct_sales = float(vals[0])
        elif lab == 'Phasing %' and len(vals) >= 12:
            phasing = [float(v) for v in vals[:12]]
    if annual:
        out['CHC'] = {'fy': annual, 'phasing': phasing, 'source': 'CHC_BU_YTD_PERFROMANCE.xlsx / New CHC Target'}
        if pct_sales:
            out['CHC_SALES'] = {'fy': annual * pct_sales, 'phasing': phasing, 'source': 'CHC_BU_YTD_PERFROMANCE.xlsx / New CHC Target (CHC_SALES = %.0f%% of CHC)' % (100 * pct_sales)}
    log('FY targets: ' + (', '.join(f'{k} {v["fy"]/1e6:.1f}M' for k, v in out.items()) or 'none'))
    return out


def landing(E, lines, kind, fy_targets, sales_months):
    """Run-rate projection (arithmetic, not a forecast): YTD actual + the
    average of the last 3 months x remaining months. Required monthly sales to
    reach the full-year target only where one exists."""
    mA = E['sales']['mA']; n = len(mA); rem = 12 - n
    pace = sum(mA[-3:]) / min(3, n)
    ytdA = sum(mA); ytdO = sum(E['sales']['mO'])
    res = {'pace': pace, 'paceMonths': sales_months[-3:], 'remMonths': rem, 'landing': ytdA + pace * rem,
           'fy': None, 'required': None, 'fySource': None}
    key = lines[0] if kind == 'line' else ('CHC' if kind == 'bu' and lines[0] == 'CHC' else None)
    t = fy_targets.get(key) if key else None
    if t:
        res['fy'] = t['fy']; res['fySource'] = t['source']
        res['required'] = (t['fy'] - ytdA) / rem if rem else None
    return res


