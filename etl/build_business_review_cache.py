def build_brand_map(sales, iq):
    """Links sales brands to IQVIA Zeta products through Business Review/Brand_IQVIA_Map.xlsx.
    If the file does not exist a DRAFT is written: 'Auto' = the sales brand name is the
    start of the IQVIA product name AND the product sells in one of the brand's lines;
    every other candidate is 'Review' and is NOT used until Ahmed sets it to 'Confirmed'.
    The file is never overwritten once it exists."""
    try:
        import openpyxl
    except ImportError:
        log('brand map: openpyxl not installed -- sell-in vs IQVIA skipped')
        return {'groups': [], 'review': 0, 'unmapped': 0, 'file': None}
    brands = sales['brandLines']
    if not os.path.exists(MAP_XLSX):
        os.makedirs(BR_DIR, exist_ok=True)
        rows = []
        bn = {b: _norm(b) for b in brands}
        for prod, lines_v in sorted(iq['zetaProdLines'].items(), key=lambda kv: -sum(kv[1].values())):
            tot = sum(lines_v.values())
            pl = [IQ2SALES_LINE.get(l, l) for l, _ in sorted(lines_v.items(), key=lambda kv: -kv[1])]
            pn = _norm(prod)
            cands = [b for b in brands if pn.startswith(bn[b])]
