def build_managers(months_labels):
    co, _ = load_b64('coaching.data.js')
    months = co['period']['months']
    agg = collections.defaultdict(lambda: [0, 0, 0, 0, 0])
    for m in co['managers']:
        if m.get('title') not in ('District Manager', 'District Sales Manager', 'Senior District Manager'):
            continue
        ln = KEY2LINE.get(K(m.get('line')))
        if not ln:
            continue
        for mo, x in (m.get('monthly') or {}).items():
            if not x or not x.get('activeHalfMonth'):
                continue
            a = agg[(ln, mo)]
            a[0] += x.get('visits') or 0; a[1] += x.get('coachingDays') or 0
            a[2] += x.get('coachedOnRoster') or 0; a[3] += x.get('activeTeamSize') or 0; a[4] += 1
    wd, _ = load_b64('working_days.data.js')
    fd = collections.defaultdict(list)
    wmonths = wd['monthOrder']
    for mname, rows in wd['employees'].get('DM_DSM', {}).items():
        for e in rows:
            ln = KEY2LINE.get(K(e.get('line')))
            if ln and e.get('fieldPct') is not None:
                fd[(ln, mname)].append(e['fieldPct'])
    out = {'coachMonths': months, 'fieldMonths': wmonths, 'lines': {}}
    for ln in ALL_LINES:
        cm = []
        for mo in months:
            a = agg.get((ln, mo))
            cm.append({'vis': a[0], 'days': a[1], 'coached': a[2], 'team': a[3], 'dms': a[4]} if a and a[1] else None)
        fm = []
        for mo in wmonths:
            v = fd.get((ln, mo))
            fm.append({'avg': sum(v) / len(v), 'low': sum(1 for p in v if p < 0.7), 'n': len(v)} if v else None)
        out['lines'][ln] = {'coach': cm, 'field': fm}
    log(f'managers: coaching {months[0]}..{months[-1]}, field days {wmonths[0]}..{wmonths[-1]}')
    return out


# ============================================================ 4. IQVIA
def build_iqvia(mode='YTD'):
    """mode 'YTD' = Jan..latest month vs the same months last year (drives all comments);
    mode 'MAT' = the latest 12 months vs the 12 months before (display toggle only)."""
    flat, raw = load_b64('iqvia.data.js')
    m = re.search(r'"?b64Data"?\s*:\s*"[^"]+"', raw)
    rest = raw[:m.start()] + '"b64Data":""' + raw[m.end():]
    meta = json.loads(rest[rest.index('{'):rest.rindex('}') + 1])
    LK = meta['lookups']
    P = LK['periods']; corps = LK['corps']; prods = LK['prods']; dm1s = LK['dm1s']
    lines = LK['lines']; bus = LK['bus']
    latest = P[-1]; ly, lm = int(latest[:4]), int(latest[5:7])
    if mode == 'MAT':
        mi = lambda p: int(p[:4]) * 12 + int(p[5:7]) - 1
        L = mi(latest)
        cur = {i for i, p in enumerate(P) if L - 11 <= mi(p) <= L}
        prv = {i for i, p in enumerate(P) if L - 23 <= mi(p) <= L - 12}
        if len(cur) < 12 or len(prv) < 12:
            log(f'iqvia MAT: only {len(cur)}/{len(prv)} months available -- MAT skipped')
            return None
    else:
        cur = {i for i, p in enumerate(P) if int(p[:4]) == ly and int(p[5:7]) <= lm}
        prv = {i for i, p in enumerate(P) if int(p[:4]) == ly - 1 and int(p[5:7]) <= lm}
    last_i = len(P) - 1; prev_m = last_i - 1
    zeta = next(i for i, c in enumerate(corps) if 'ZETA PHARM' in c.upper())
    other = dm1s.index('OTHER MARKET') if 'OTHER MARKET' in dm1s else -99
    N = len(flat)
    # --- pass 1: entity (bu / line) markets + corp shares, dm1 markets, product totals
    ent = collections.defaultdict(lambda: [0.0] * 12)   # key -> [zV,tV,zVp,tVp,zS,tS,zSp,tSp, zVm,tVm,zVpm,tVpm(month)]
    corp_ent = collections.defaultdict(lambda: [0.0, 0.0])  # (entkey, corp) -> [cur V, prev V]
    corp_prod_ent = collections.defaultdict(lambda: [0.0, 0.0])  # (entkey, corp, prod) -> [cur V, prev V]
    dm1_tot = collections.defaultdict(lambda: [0.0, 0.0, 0.0, 0.0])  # dm1 -> [V, Vp, S, Sp]
    prod_dm1 = collections.defaultdict(lambda: [0.0, 0.0, 0.0, 0.0])  # (prod, dm1) -> [V,Vp,S,Sp]
    prod_corp = {}
    zeta_prod_line = collections.defaultdict(float)  # (prod, line) -> cur V
    zp_month = collections.defaultdict(float)         # (prod, period) -> V, all DM1s incl. OTHER MARKET
    zp_lines = collections.defaultdict(collections.Counter)
    for i in range(0, N, 14):
        d1 = flat[i + 4]
        if flat[i] == zeta:
            tz = flat[i + 2]
            if tz in cur or tz in prv:
                zp_month[(prods[flat[i + 1]], P[tz])] += flat[i + 6]
                if tz in cur:
                    li_ = flat[i + 8]
                    zp_lines[prods[flat[i + 1]]][lines[li_] if 0 <= li_ < len(lines) else '-'] += flat[i + 6]
        if d1 == other:
            continue
        t = flat[i + 2]
        ic, ip = t in cur, t in prv
        im, ipm = t == last_i, t == prev_m
        if not (ic or ip or im or ipm):
            continue
        c = flat[i]; pr = flat[i + 1]; v = flat[i + 6]; su = flat[i + 7]
        li = flat[i + 8]; bi = flat[i + 9]; z = c == zeta
        keys = []
        if 0 <= bi < len(bus):
            keys.append('BU:' + bus[bi])
            if bus[bi] in BU_LINES:
                keys.append('ALL')   # the 4 promoted BUs (Non-Promoted / Other Markets excluded)
            if 0 <= li < len(lines):
                keys.append('LINE:' + lines[li])
        for k in keys:
            e = ent[k]
            if ic:
                e[1] += v; e[5] += su
                if z: e[0] += v; e[4] += su
                corp_ent[(k, c)][0] += v
                corp_prod_ent[(k, c, pr)][0] += v
            if ip:
                e[3] += v; e[7] += su
                if z: e[2] += v; e[6] += su
                corp_ent[(k, c)][1] += v
                corp_prod_ent[(k, c, pr)][1] += v
            if im:
                e[9] += v
                if z: e[8] += v
            if ipm:
                e[11] += v
                if z: e[10] += v
        if ic or ip:
            dt = dm1_tot[d1]; pd = prod_dm1[(pr, d1)]
            if ic:
                dt[0] += v; dt[2] += su; pd[0] += v; pd[2] += su
                if z and 0 <= li < len(lines):
                    zeta_prod_line[(pr, lines[li])] += v
            else:
                dt[1] += v; dt[3] += su; pd[1] += v; pd[3] += su
            prod_corp[pr] = c
    del flat
    # --- products of each company inside each entity market
    cprods = collections.defaultdict(list)   # (k, corp) -> [(prod, V, Vp)]
    for (k, c, pr), v in corp_prod_ent.items():
        cprods[(k, c)].append((pr, v[0], v[1]))
    del corp_prod_ent

    def prod_list(k, c, e, n=3, by='value'):
        """Top products of company c in entity k. by='value' -> largest YTD value;
        by='gain'/'loss' -> largest share-point change (each product's share of the
        entity market now minus last period)."""
        rows = []
        for pr, v, vp in cprods.get((k, c), []):
            s = div(v, e[1]) or 0; sp = div(vp, e[3]) or 0
            rows.append({'prod': prods[pr], 'share': s, 'shareP': sp, 'dShare': s - sp,
                         'growth': (v / vp - 1) if vp else None, 'v': v})
        if by == 'gain':
            rows = [r for r in rows if r['dShare'] > 0]; rows.sort(key=lambda r: -r['dShare'])
        elif by == 'loss':
            rows = [r for r in rows if r['dShare'] < 0]; rows.sort(key=lambda r: r['dShare'])
        else:
            rows = [r for r in rows if r['v'] > 0]; rows.sort(key=lambda r: -r['v'])
        return [{kk: r[kk] for kk in ('prod', 'share', 'shareP', 'dShare', 'growth')} for r in rows[:n]]

    # --- entity summaries
    def ent_summary(k):
        e = ent.get(k)
        if not e or not e[1]:
            return None
        cs = [(c, v[0], v[1]) for (kk, c), v in corp_ent.items() if kk == k]
        cs.sort(key=lambda x: -x[1])
        csp = sorted(cs, key=lambda x: -x[2])
        rank_now = next((i + 1 for i, x in enumerate(cs) if x[0] == zeta), None)
        rank_prev = next((i + 1 for i, x in enumerate(csp) if x[0] == zeta), None)
        top = []
        for c, v, vp in cs[:8]:
            top.append({'corp': corps[c], 'zeta': c == zeta, 'share': div(v, e[1]), 'shareP': div(vp, e[3]),
                        'growth': (v / vp - 1) if vp else None, 'prods': prod_list(k, c, e, 3, 'value')})
        movers = []
        for c, v, vp in cs:
            s = div(v, e[1]) or 0
            if s < TH['minShare'] or not vp:
                continue
            movers.append({'corp': corps[c], 'zeta': c == zeta, 'share': s, 'dShare': s - (div(vp, e[3]) or 0), 'growth': v / vp - 1, '_c': c})
        movers.sort(key=lambda x: -x['dShare'])
        gainers, losers = movers[:3], movers[::-1][:3]
        for m_ in gainers:
            m_['prods'] = prod_list(k, m_['_c'], e, 2, 'gain')
        for m_ in losers:
            m_['prods'] = prod_list(k, m_['_c'], e, 2, 'loss')
        for m_ in movers:
            m_.pop('_c', None)
        return {
            'shareSU': div(e[4], e[5]), 'shareSUp': div(e[6], e[7]),
            'shareV': div(e[0], e[1]), 'shareVp': div(e[2], e[3]),
            'mktV': e[1], 'mktVp': e[3], 'zV': e[0], 'zVp': e[2],
            'mktG': (e[1] / e[3] - 1) if e[3] else None, 'zG': (e[0] / e[2] - 1) if e[2] else None,
            'evi': round(100 * (e[4] / e[6]) / (e[5] / e[7])) if e[6] and e[7] else None,   # SU basis, as getBlendedBuShare
            'eviV': round(100 * (e[0] / e[2]) / (e[1] / e[3])) if e[2] and e[3] else None,
            'shareVm': div(e[8], e[9]), 'shareVpm': div(e[10], e[11]),
            'rank': rank_now, 'rankP': rank_prev, 'nCorps': len(cs),
            'topCorps': top, 'gainers': gainers, 'losers': losers,
        }
    ents = {'ALL': ent_summary('ALL')}
    for b in BU_LINES:
        ents['BU:' + b] = ent_summary('BU:' + b)
    for ln in ALL_LINES:
        iql = IQ_LINE_OF.get(ln, ln)
        ents['LINE:' + ln] = ent_summary('LINE:' + iql)
    # --- brand (Zeta product) analysis in its main DM1 market
    zeta_prods = collections.defaultdict(float)
    for (pr, d1), v in prod_dm1.items():
        if prod_corp.get(pr) == zeta:
            zeta_prods[pr] += v[0]
    by_dm1 = collections.defaultdict(list)
    for (pr, d1), v in prod_dm1.items():
        by_dm1[d1].append((pr, v))
    brands = {}
    for pr, vtot in zeta_prods.items():
        if vtot <= 0:
            continue
        # main dm1 by current value
        cands = [(d1, v) for (p, d1), v in prod_dm1.items() if p == pr]
        d1, v = max(cands, key=lambda x: x[1][0])
        mt = dm1_tot[d1]
        if not mt[0]:
            continue
        # line of this product (Zeta rows' line tag, by value)
        pl = [(l, x) for (p, l), x in zeta_prod_line.items() if p == pr]
        pline = max(pl, key=lambda x: x[1])[0] if pl else None
        comp = []
        for p2, v2 in by_dm1[d1]:
            s = div(v2[0], mt[0]) or 0
            sp = div(v2[1], mt[1]) or 0
            comp.append({'prod': prods[p2], 'corp': corps[prod_corp.get(p2, 0)], 'zeta': prod_corp.get(p2) == zeta,
                         'share': s, 'shareP': sp, 'growth': (v2[0] / v2[1] - 1) if v2[1] else None, 'v': v2[0]})
        comp.sort(key=lambda x: -x['v'])
        rank = next((i + 1 for i, x in enumerate(comp) if x['prod'] == prods[pr]), None)
        prank_list = sorted(comp, key=lambda x: -x['shareP'])
